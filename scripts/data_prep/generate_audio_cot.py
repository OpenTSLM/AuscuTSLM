DEFAULT_PATIENT_SPLITS_PATH = "data/caresound_patient_splits.json"


def load_caresound_dataset(cache_dir=None, patient_splits_path=DEFAULT_PATIENT_SPLITS_PATH):
    """Load CaReSound dataset from HuggingFace, split by patient-level mapping.

    If ``patient_splits_path`` exists, the HuggingFace rows are pooled and
    re-assigned to ``train`` / ``val`` / ``test`` according to the patient
    mapping (no patient overlap between splits).

    Falls back to the legacy HF train/test split when no mapping file exists.

    Returns:
        dict[str, list[dict]]  —  ``{"train": [...], "val": [...], "test": [...]}``
    """
    print("Loading CaReSound dataset from HuggingFace...")
    hf_dataset = load_dataset("tsnngw/CaReSound", cache_dir=cache_dir)
    print(f"  HF train: {len(hf_dataset['train'])} rows")
    print(f"  HF test:  {len(hf_dataset['test'])} rows")

    use_patient_split = (
        patient_splits_path is not None
        and os.path.exists(patient_splits_path)
    )

    if use_patient_split:
        with open(patient_splits_path) as f:
            split_map = json.load(f)["splits"]  # patient_id → "train"/"val"/"test"
        print(f"  Patient-level split loaded ({len(split_map)} patients)")

        # Pool ALL HF rows and redistribute
        splits = {"train": [], "val": [], "test": []}
        unmapped = 0
        for hf_split_name in ("train", "test"):
            for row in hf_dataset[hf_split_name]:
                pid = str(row["patient_id"])
                assigned = split_map.get(pid)
                if assigned in splits:
                    splits[assigned].append(dict(row))
                else:
                    unmapped += 1

        for s_name in ("train", "val", "test"):
            print(f"  {s_name}: {len(splits[s_name])} QA pairs (patient-disjoint)")
        if unmapped:
            print(f"  ⚠ {unmapped} rows with unmapped patient_id (skipped)")
        return splits
    else:
        print("  ⚠ No patient split file found — using legacy HF train/test (val = test copy)")
        return {
            "train": [dict(row) for row in hf_dataset["train"]],
            "val":   [dict(row) for row in hf_dataset["test"]],
            "test":  [dict(row) for row in hf_dataset["test"]],
        }

def process_audio_sample(
    sample,
    audio_dir,
    spectrogram_dir,
    use_mini=True,
    save_spectrograms=False
):
    """
    Process a single audio sample to generate CoT rationale.

    Args:
        sample: Dataset sample with patient_id, question, answer, dataset
        audio_dir: Directory containing audio files
        spectrogram_dir: Directory to save spectrograms
        use_mini: Use GPT-4o-mini (cheaper)
        save_spectrograms: Save spectrograms to disk (for debugging)

    Returns:
        Dictionary with processed data or None if failed
    """
    patient_id = sample["patient_id"]
    question = sample["question"]
    answer = sample["answer"]
    dataset_name = sample.get("dataset", "Medical")

    # Find audio file(s) — supports flat dir, subdirs, and suffixed names
    audio_paths = _find_audio_files(patient_id, dataset_name, audio_dir)

    if not audio_paths:
        return None

    # Select the best audio file for this specific question
    # (e.g., tracheal recording for "wheezes at tracheal location?" questions)
    audio_path, loc_code = _select_audio_for_question(audio_paths, question, dataset_name)

    try:
        # Spectrogram name matches the audio filename (minus extension)
        # e.g. 130_1p2_Tc_mc_AKGC417L.wav → 130_1p2_Tc_mc_AKGC417L.png
        audio_basename = os.path.splitext(os.path.basename(audio_path))[0]
        spec_name = f"{audio_basename}.png"
        spectrogram_path = os.path.join(spectrogram_dir, spec_name)
        os.makedirs(spectrogram_dir, exist_ok=True)
        if not os.path.exists(spectrogram_path):
            # Load audio and preprocess to 1D mono
            waveform, sr = load_audio(audio_path, target_sample_rate=16000)
            waveform = preprocess_audio(waveform, sample_rate=sr, target_sample_rate=16000)
            audio_data = waveform.numpy()
            generate_spectrogram_image(audio_data, sample_rate=16000, output_path=spectrogram_path)

        # Generate CoT rationale
        prompt, rationale, usage = generate_audio_cot_rationale(
            spectrogram_path=spectrogram_path,
            question=question,
            answer=answer,
            dataset_name=dataset_name,
            patient_id=patient_id,
            use_mini=use_mini
        )

        # Clean up spectrogram if not saving
        if not save_spectrograms:
            try:
                os.remove(spectrogram_path)
            except FileNotFoundError:
                pass

        return {
            "patient_id": patient_id,
            "dataset": dataset_name,
            "question": question,
            "answer": answer,
            "rationale": rationale,
            "prompt": prompt,
            "audio_file": os.path.basename(audio_path),
            "_usage": usage,  # token usage for cost tracking
        }

    except Exception as e:
        print(f"Error processing patient {patient_id}: {e}")
        return None

