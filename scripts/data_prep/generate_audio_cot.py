# CoT Generation with Vision API
# ---------------------------
def generate_audio_cot_rationale(
    spectrogram_path,
    question,
    answer,
    dataset_name,
    patient_id,
    use_mini=True
):
    """
    Use GPT-4o-mini to generate Chain-of-Thought reasoning from spectrogram.

    Args:
        spectrogram_path: Path to spectrogram image
        question: Diagnostic question
        answer: Ground truth answer
        dataset_name: Name of dataset (ICBHI, CirCor, etc.)
        patient_id: Patient ID
        use_mini: Use gpt-4o-mini (cheaper) instead of gpt-4o

    Returns:
        Tuple of (prompt, rationale)
    """
    # Create prompt
    prompt = create_audio_classification_prompt(question, answer, dataset_name)

    # Read and encode image
    with open(spectrogram_path, "rb") as image_file:
        image_data = base64.b64encode(image_file.read()).decode('utf-8')

    # Call GPT-4o-mini vision API
    model = "gpt-4o-mini" if use_mini else "gpt-4o"

    max_retries = 5
    for attempt in range(max_retries):
        try:
            response = client.chat.completions.create(
                model=model,
                messages=[
                    {
                        "role": "system",
                        "content": SYSTEM_PROMPT,
                    },
                    {
                        "role": "user",
                        "content": [
                            {"type": "text", "text": prompt},
                            {
                                "type": "image_url",
                                "image_url": {
                                    "url": f"data:image/png;base64,{image_data}",
                                    "detail": "high"
                                }
                            }
                        ]
                    }
                ],
                temperature=0.7,
                max_tokens=500,
                seed=42
            )

            rationale = response.choices[0].message.content.strip()

            # Extract token usage
            usage = {
                "prompt_tokens": getattr(response.usage, "prompt_tokens", 0),
                "completion_tokens": getattr(response.usage, "completion_tokens", 0),
                "total_tokens": getattr(response.usage, "total_tokens", 0),
            }

            # Ensure it ends with "Answer: {answer}"
            if not rationale.endswith(f"Answer: {answer}"):
                # Try to find where answer was mentioned
                if f"Answer: {answer}" in rationale:
                    # Already has it somewhere, just ensure it's at the end
                    parts = rationale.split(f"Answer: {answer}")
                    rationale = parts[0].strip() + f" Answer: {answer}"
                else:
                    # Add it
                    rationale = rationale.strip() + f" Answer: {answer}"

            return prompt, rationale, usage

        except Exception as e:
            error_str = str(e)
            if "429" in error_str or "rate_limit" in error_str.lower():
                # Parse wait time from error message (e.g. "Please try again in 321ms")
                wait = 1.0  # default fallback
                match = re.search(r"try again in (\d+)(ms|s)", error_str)
                if match:
                    val = int(match.group(1))
                    unit = match.group(2)
                    wait = val / 1000.0 if unit == "ms" else float(val)
                wait = max(wait, 0.5) * (1.5 ** attempt)  # exponential backoff
                if attempt < max_retries - 1:
                    time.sleep(wait)
                    continue
            # Non-retryable error or exhausted retries
            print(f"Error calling OpenAI API for patient {patient_id}: {e}")
            return prompt, f"Unable to generate rationale. Answer: {answer}", {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0}

    # Should not reach here, but just in case
    return prompt, f"Unable to generate rationale. Answer: {answer}", {"prompt_tokens": 0, "completion_tokens": 0, "total_tokens": 0}

def create_audio_classification_prompt(question, correct_answer, dataset_name):
    """
    Create user-side prompt for audio CoT generation.

    Designed to elicit clinically grounded, spectrogram-anchored reasoning
    that connects signal → physiology → diagnosis.

    Args:
        question: Diagnostic question
        correct_answer: Ground truth answer
        dataset_name: Dataset name (e.g. SPRSound, ICBHI, CirCor)

    Returns:
        Prompt string
    """
    prompt = f"""You are analyzing a mel-spectrogram from a {dataset_name} auscultation recording.

Question: {question}

The correct answer is: {correct_answer}

Provide a clinically grounded reasoning paragraph based on the spectrogram characteristics that leads to the answer "{correct_answer}".
End with "Answer: {correct_answer}"

Answer:"""
    return prompt

