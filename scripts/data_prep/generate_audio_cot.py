def generate_spectrogram_image(audio_data, sample_rate=16000, output_path=None):
    """
    Generate mel-spectrogram visualization for GPT-4o-mini to analyze.

    Args:
        audio_data: Audio waveform (numpy array)
        sample_rate: Sample rate in Hz
        output_path: Path to save PNG (if None, saves to temp file)

    Returns:
        Path to saved spectrogram image
    """
    try:
        import librosa
        import librosa.display
    except ImportError:
        raise ImportError("librosa is required. Install with: pip install librosa")

    # Generate mel-spectrogram
    mel_spec = librosa.feature.melspectrogram(
        y=audio_data,
        sr=sample_rate,
        n_mels=128,
        fmax=8000,
        hop_length=512
    )
    mel_spec_db = librosa.power_to_db(mel_spec, ref=np.max)

    # Create figure
    fig, ax = plt.subplots(figsize=(12, 6))
    img = librosa.display.specshow(
        mel_spec_db,
        sr=sample_rate,
        x_axis='time',
        y_axis='mel',
        fmax=8000,
        ax=ax
    )
    fig.colorbar(img, ax=ax, format='%+2.0f dB')
    ax.set_title('Mel-Spectrogram')
    plt.tight_layout()

    # Save
    if output_path is None:
        output_path = "temp_spectrogram.png"

    plt.savefig(output_path, dpi=150, bbox_inches='tight')
    plt.close(fig)

    return output_path

