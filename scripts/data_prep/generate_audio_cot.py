# ── ICBHI: lung auscultation location codes ──
# Filenames: {patient}_{session}p{channel}_{location}_{mode}_{device}.wav
_ICBHI_LOCATION_MAP = {
    "Tc": ["tracheal", "trachea"],
    "Al": ["anterior left"],
    "Ar": ["anterior right"],
    "Pl": ["posterior left"],
    "Pr": ["posterior right"],
    "Ll": ["lateral left"],
    "Lr": ["lateral right"],
}
_ICBHI_KEYWORD_TO_CODE = {}
for _code, _keywords in _ICBHI_LOCATION_MAP.items():
    for _kw in _keywords:
        _ICBHI_KEYWORD_TO_CODE[_kw] = _code

# ── CirCor: cardiac valve location codes ──
# Filenames: {patient}_{valve}.wav  (AV, MV, PV, TV)
_CIRCOR_LOCATION_MAP = {
    "AV": ["aortic valve", "aortic"],
    "MV": ["mitral valve", "mitral"],
    "PV": ["pulmonic valve", "pulmonic", "pulmonary valve", "pulmonary"],
    "TV": ["tricuspid valve", "tricuspid"],
}
_CIRCOR_KEYWORD_TO_CODE = {}
for _code, _keywords in _CIRCOR_LOCATION_MAP.items():
    for _kw in _keywords:
        _CIRCOR_KEYWORD_TO_CODE[_kw] = _code


def _extract_location_from_question(question, dataset_name):
    """
    Extract body/valve location from a question string.

    Returns a location code suitable for filename matching:
      - ICBHI:  'Tc', 'Pl', 'Ar', ... (matched via _{code}_ in filename)
      - CirCor: 'AV', 'MV', 'PV', 'TV' (matched via _{code}. in filename)
      - Others: None
    """
    q_lower = question.lower()

    if dataset_name == "ICBHI":
        for keyword, code in _ICBHI_KEYWORD_TO_CODE.items():
            if keyword in q_lower:
                return code

    elif dataset_name == "CirCor":
        for keyword, code in _CIRCOR_KEYWORD_TO_CODE.items():
            if keyword in q_lower:
                return code

    # SPRSound: questions don't reference specific positions (p1-p4)
    # ZCHSound / KAUH: single file per patient
    return None


def _find_audio_files(patient_id, dataset_name, audio_dir):
    """
    Find audio file(s) for a patient, searching flat dir, subdirs, and suffixed names.
    
    Supports:
      - Flat exact:      audio_dir/{patient_id}.wav
      - Flat suffixed:   audio_dir/{patient_id}_*.wav  (e.g. _p1, _AV, _MV)
      - Subdir exact:    audio_dir/{dataset}/{patient_id}.wav
      - Subdir suffixed: audio_dir/{dataset}/{patient_id}_*.wav
    """
    extensions = [".wav", ".flac", ".mp3", ".ogg"]
    found = []
    for ext in extensions:
        # Flat exact
        exact = os.path.join(audio_dir, f"{patient_id}{ext}")
        if os.path.exists(exact):
            found.append(exact)
        # Flat suffixed
        for p in glob.glob(os.path.join(audio_dir, f"{patient_id}_*{ext}")):
            if p not in found:
                found.append(p)
        # Subdir exact
        sub_exact = os.path.join(audio_dir, dataset_name, f"{patient_id}{ext}")
        if os.path.exists(sub_exact) and sub_exact not in found:
            found.append(sub_exact)
        # Subdir suffixed
        for p in glob.glob(os.path.join(audio_dir, dataset_name, f"{patient_id}_*{ext}")):
            if p not in found:
                found.append(p)
    return sorted(found)


def _select_audio_for_question(audio_paths, question, dataset_name):
    """
    Select the best audio file for a given question.

    Location-aware matching:
      - ICBHI:  "wheezes at tracheal?" → file with _Tc_ in name
      - CirCor: "murmur at aortic valve?" → file with _AV in name
      - Others: first file (no location info in questions)

    Args:
        audio_paths: List of audio file paths for this patient
        question: The diagnostic question text
        dataset_name: Dataset name (e.g. 'ICBHI', 'CirCor', 'SPRSound')

    Returns:
        (selected_path, location_code_or_None)
    """
    if not audio_paths:
        return None, None

    loc_code = _extract_location_from_question(question, dataset_name)
    if loc_code is None:
        # General question or dataset without location matching
        return audio_paths[0], None

    # Search for the matching file
    for path in audio_paths:
        basename = os.path.basename(path)
        if dataset_name == "ICBHI":
            # ICBHI: location is mid-filename, e.g. 130_1p2_Tc_mc_AKGC417L.wav
            if f"_{loc_code}_" in basename:
                return path, loc_code
        elif dataset_name == "CirCor":
            # CirCor: valve is suffix, e.g. 50214_AV.wav
            name_no_ext = os.path.splitext(basename)[0]
            if name_no_ext.endswith(f"_{loc_code}"):
                return path, loc_code

    # No matching file found — fall back to first
    return audio_paths[0], None


