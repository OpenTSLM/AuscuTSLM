"""
CaReSound Chain-of-Thought (CoT) dataset for audio question answering with reasoning.

This dataset extends CareSoundDataset by adding GPT-4o-generated chain-of-thought
rationales that provide step-by-step reasoning for diagnostic decisions.
"""

import os
import pandas as pd
from typing import List, Tuple
from datasets import Dataset

from opentslm.time_series_datasets.audio.CareSoundDataset import CareSoundDataset
from opentslm.prompt.text_time_series_prompt import TextTimeSeriesPrompt


class CareSoundCoTDataset(CareSoundDataset):
    """
    CaReSound dataset with Chain-of-Thought reasoning.

    Extends CareSoundDataset to include step-by-step diagnostic reasoning
    generated by GPT-4o-mini on audio spectrograms.

    Args:
        split: Dataset split ('train' or 'test')
        EOS_TOKEN: End-of-sequence token
        audio_dir: Directory containing audio files
        cot_data_dir: Directory containing CoT CSV files (default: data/caresound_cot)
        cache_dir: Directory to cache downloaded HuggingFace metadata
        sample_rate: Target sample rate for audio (default: 16000 Hz)
        max_audio_length: Maximum audio length in samples (default: 480000 = 30s at 16kHz)
    """

    def __init__(
        self,
        split: str,
        EOS_TOKEN: str,
        audio_dir: str = "./data/caresound_audio/audio_merged",
        cot_data_dir: str = "data/caresound_cot",
        cache_dir: str = None,
        sample_rate: int = 16000,
        max_audio_length: int = 480000,
    ):
        # Initialize parent class
        super().__init__(
            split=split,
            EOS_TOKEN=EOS_TOKEN,
            audio_dir=audio_dir,
            cache_dir=cache_dir,
            sample_rate=sample_rate,
            max_audio_length=max_audio_length,
        )

        # Load CoT rationales from CSV
        self.cot_data_dir = cot_data_dir
        self._load_cot_rationales(split)

    def _load_cot_rationales(self, split: str):
        """Load CoT rationales from CSV file(s).

        With the patient-level split, samples in any split can originate from
        either the old HF train or test data.  We therefore load ALL available
        CoT CSV files and build a combined lookup keyed on (patient_id, question).
        """
        # Load all available CoT CSVs to build a combined lookup
        csv_candidates = [
            os.path.join(self.cot_data_dir, "caresound_train_cot.csv"),
            os.path.join(self.cot_data_dir, "caresound_test_cot.csv"),
            os.path.join(self.cot_data_dir, "caresound_val_cot.csv"),
        ]
        loaded_any = False

        self.cot_lookup = {}
        for csv_file in csv_candidates:
            if not os.path.exists(csv_file):
                continue
            print(f"Loading CoT rationales from {csv_file}...")
            df = pd.read_csv(csv_file)
            for _, row in df.iterrows():
                patient_id = str(row['patient_id'])
                question = str(row['question'])
                key = (patient_id, question)
                if key not in self.cot_lookup:
                    self.cot_lookup[key] = {
                        'rationale': row['rationale'],
                        'prompt': row.get('prompt', ''),
                    }
            loaded_any = True

        if not loaded_any:
            raise FileNotFoundError(
                f"No CoT CSV files found in {self.cot_data_dir}\n"
                f"Please run: python scripts/data_prep/generate_audio_cot.py to generate CoT rationales"
            )

        print(f"  Loaded {len(self.cot_lookup)} unique CoT rationales (combined)")

        # Warn if coverage is low
        total_samples = len(self)
        hf_splits = self._hf_splits
        matched = 0
        for hf_idx, row_idx in self._index_map:
            row = hf_splits[hf_idx][row_idx]
            if (str(row['patient_id']), str(row['question'])) in self.cot_lookup:
                matched += 1
        coverage = 100.0 * matched / total_samples if total_samples > 0 else 0
        print(f"  Coverage: {matched}/{total_samples} samples ({coverage:.1f}%)")

        if coverage < 90:
            print(f"  ⚠️  Warning: Low CoT coverage. Some samples will use original short answers.")

    def _format_sample(self, row):
        """Format a single sample with CoT rationale.

        Calls the parent ``_format_sample`` (which goes through
        ``PromptWithAnswer.to_dict()``) so all required keys –
        especially ``time_series`` – are present.  Then swaps the
        answer with the CoT rationale when available.
        """
        # Get CoT rationale if available (keyed on patient_id + question)
        patient_id = str(row['patient_id'])
        question = str(row['question'])
        cot_data = self.cot_lookup.get((patient_id, question))

        if cot_data:
            cot_answer = cot_data['rationale']
        else:
            cot_answer = None

        # Call parent to get the fully-formed dict (with time_series key)
        formatted = super()._format_sample(row)

        # Swap answer with CoT rationale (keep original for eval)
        formatted['original_answer'] = row['answer']
        if cot_answer is not None:
            # Replace the short answer with the CoT rationale
            # Re-add EOS token if needed
            if not cot_answer.endswith(self.EOS_TOKEN):
                cot_answer += self.EOS_TOKEN
            formatted['answer'] = cot_answer

        # Add metadata
        formatted['patient_id'] = patient_id
        formatted['dataset'] = row.get('dataset', 'Medical')
        formatted['question'] = row['question']

        return formatted

    def _get_pre_prompt(self, row) -> str:
        """Get the pre-prompt for audio CoT QA.
        
        Aligned with the generation prompt in generate_audio_cot.py:
        the model learns to produce clinically grounded, spectrogram-anchored
        reasoning that connects signal → physiology → diagnosis.
        """
        dataset_name = row.get("dataset", "medical")

        prompt = f"""You are a clinical audio reasoning assistant specialized in cardiac and respiratory auscultation analysis.

Your task is to analyze the audio from a {dataset_name} auscultation recording and produce a clinically grounded reasoning paragraph that connects observed acoustic features to physiological interpretation and clinical diagnosis.

- Your reasoning must be evidence-based and grounded in the specific audio signal.
- Reference at least one temporal feature (e.g., inspiratory/expiratory pattern), one frequency-related feature (e.g., high-frequency components), and one morphology feature (e.g., harmonic streaks, vertical spikes).
- Avoid generic descriptions or systematic negation of abnormalities.
- Explicitly reason step by step: observe features, interpret them in physiological terms, then conclude with the answer.
- Each paragraph should be coherent, 120–180 words, and mention the final answer ONLY in the last sentence, formatted as "Answer: <answer>".
- Ensure your reasoning is specific to this recording and would not apply verbatim to a different case.

Analyze the following audio (or mel-spectrogram representation) carefully:"""


        return prompt.strip()

    def _get_post_prompt(self, row) -> str:
        """Get the question as post-prompt."""
        question = row["question"]
        return f"\nQuestion: {question}\n\nRationale:"


