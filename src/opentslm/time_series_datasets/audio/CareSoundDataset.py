"""
CaReSound dataset for cardiac and respiratory sound question answering.

CaReSound is a multimodal benchmark dataset for diagnostic reasoning using
cardiac and respiratory auscultation audio with question-answer pairs.

Dataset: https://huggingface.co/datasets/tsnngw/CaReSound

The dataset contains:
- ~32,600 total QA pairs from 2,951 patients
- Audio from 5 sources: ICBHI, CirCor, SPRSound, ZCHSound, KAUH
- Mean audio duration: ~18.75 seconds
- Task: Medical diagnostic question answering

Split modes:
  1. Patient-level (recommended): uses data/caresound_patient_splits.json
     - 70% train / 15% val / 15% test by patient (no patient overlap)
     - Generate with: python scripts/data_prep/create_patient_splits.py
  2. Legacy HF split (fallback): original question-level train/test split
     - Same patient can appear in both splits (data leakage risk)

**IMPORTANT**: The HuggingFace dataset only contains metadata (patient_id, question, answer).
You must download the audio files separately and provide the path via `audio_dir`.

Audio file structure expected:
    # For most datasets (single file per patient):
    audio_dir/
        {patient_id}.wav  (e.g., 65109516.wav)
        {patient_id}.wav
        ...
    
    # For CirCor dataset (multiple valves per patient):
    audio_dir/
        {patient_id}_AV.wav  (Aortic Valve)
        {patient_id}_MV.wav  (Mitral Valve)
        {patient_id}_PV.wav  (Pulmonic Valve)
        {patient_id}_TV.wav  (Tricuspid Valve, optional)
        ...
    
    Note: Multiple audio files per patient_id are supported. The dataset will
    automatically load all available valve recordings and include them in the prompt.

Installation:
    pip install datasets
"""

