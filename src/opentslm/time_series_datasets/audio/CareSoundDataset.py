# Default path for patient-level split mapping
# Generated by: python scripts/data_prep/create_patient_splits.py
DEFAULT_PATIENT_SPLITS_PATH = "data/caresound_patient_splits.json"

# ---------------------------------------------------------------------------
# ICBHI chest‐location code → human‐readable label
# Filename convention:  {patient_id}_{session}_{location}_{mode}_{device}.wav
# e.g. 130_1p2_Al_mc_AKGC417L.wav  →  location = "Al"
# ---------------------------------------------------------------------------
_ICBHI_LOCATION_MAP = {
    "Al": "Anterior Left",
    "Ar": "Anterior Right",
    "Pl": "Posterior Left",
    "Pr": "Posterior Right",
    "Ll": "Lateral Left",
    "Lr": "Lateral Right",
    "Tc": "Trachea",
}


def _parse_icbhi_suffix(suffix_part: str) -> str:
    """Parse an ICBHI filename suffix into a human‐readable location label.

    ICBHI filenames follow: {pid}_{session}_{location}_{mode}_{device}
    After stripping the patient‐id prefix the remainder looks like
    ``"1p2_Al_mc_AKGC417L"`` — we extract the *location* component.

    Returns e.g. ``"Anterior Left"`` or falls back to the raw suffix
    title‐cased if the location code is unrecognised.
    """
    parts = suffix_part.split("_")
    # Typical: ["1p2", "Al", "mc", "AKGC417L"]
    # The location code is usually the 2nd component (index 1)
    if len(parts) >= 2:
        loc_code = parts[1]
        if loc_code in _ICBHI_LOCATION_MAP:
            return _ICBHI_LOCATION_MAP[loc_code]
    # Fallback: check every part against the map (handles unusual orderings)
    for part in parts:
        if part in _ICBHI_LOCATION_MAP:
            return _ICBHI_LOCATION_MAP[part]
    # Nothing matched — return title‐cased raw suffix
    return suffix_part.replace("_", " ").title()


class CareSoundDataset(QADataset):
    """
    CaReSound dataset for cardiac and respiratory sound QA.

    Uses lazy loading: only HuggingFace metadata is kept in memory.
    Audio files are loaded on-the-fly in __getitem__ to avoid OOM when
    pre-loading all 30k+ audio samples (~94 GB as numpy arrays).

    Supports two splitting modes:

    1. **Patient-level split** (recommended, default when split file exists):
       Uses a JSON mapping (``data/caresound_patient_splits.json``) that assigns
       each ``patient_id`` to exactly one of ``train`` / ``val`` / ``test``.
       All QA pairs for a patient go to the same split — no data leakage.
       Generate the file with: ``python scripts/data_prep/create_patient_splits.py``

    2. **Legacy HuggingFace split** (fallback):
       Uses the original HF ``train`` / ``test`` splits, where the same patient
       can appear in both (question-level split). This is kept for backward
       compatibility but is **not recommended** for fair evaluation.

    Clip sampling (MIL):
       When a patient has more audio recordings than ``max_clips_per_patient``,
       the dataset **randomly samples** a subset (during training) so that
       different epochs see different clips.  During evaluation the first
       ``max_clips_per_patient`` clips are used deterministically.

    Args:
        split: Dataset split — ``'train'``, ``'val'``, or ``'test'``
        EOS_TOKEN: End-of-sequence token
        audio_dir: Directory containing audio files
        patient_splits_path: Path to patient-level split JSON file.
            Set to ``None`` to force legacy HF split behaviour.
        cache_dir: Directory to cache downloaded HuggingFace metadata
        sample_rate: Target sample rate for audio (default: 16000 Hz)
        max_audio_length: Maximum audio length in samples (default: 480000 = 30s at 16kHz)
        max_clips_per_patient: Maximum number of audio clips to load per patient.
            For patients with more clips, a random subset is sampled during
            training to ensure full coverage across epochs.  Set to ``None``
            to load all clips (not recommended for patients with 60+ files).
    """

    def __init__(
        self,
        split: str,
        EOS_TOKEN: str,
        audio_dir: str = "data/caresound/audio",
        patient_splits_path: Optional[str] = DEFAULT_PATIENT_SPLITS_PATH,
        cache_dir: str = None,
        sample_rate: int = 16000,
        max_audio_length: int = 480000,
        max_clips_per_patient: Optional[int] = 8,
    ):
        self.audio_dir = audio_dir
        self.cache_dir = cache_dir
        self.sample_rate = sample_rate
        self.max_audio_length = max_audio_length
        self.EOS_TOKEN = EOS_TOKEN
        self.split = split
        self.max_clips_per_patient = max_clips_per_patient

        # --- Load HuggingFace metadata (once, shared across instances) --------
        if not hasattr(self.__class__, "_metadata_loaded"):
            print("Loading CaReSound metadata from HuggingFace (lazy mode)...")
            dataset = load_dataset("tsnngw/CaReSound", cache_dir=self.cache_dir)
            self.__class__._hf_train = dataset["train"]
            self.__class__._hf_test = dataset["test"]
            self.__class__._metadata_loaded = True
            print(
                f"  Metadata loaded: {len(self.__class__._hf_train)} HF-train, "
                f"{len(self.__class__._hf_test)} HF-test"
            )

        # --- Decide splitting mode -------------------------------------------
        use_patient_split = (
            patient_splits_path is not None
            and os.path.exists(patient_splits_path)
        )

        if use_patient_split:
            self._init_patient_split(split, patient_splits_path)
        else:
            if split == "val":
                # Legacy mode has no val — fall back to test with a warning
                print(
                    "⚠  No patient split file found and split='val' requested. "
                    "Falling back to HF 'test' split. "
                    "Run 'python scripts/data_prep/create_patient_splits.py' to create "
                    "a proper patient-disjoint split."
                )
                split = "test"
            self._init_legacy_split(split)

    # ------------------------------------------------------------------
    # Splitting helpers
    # ------------------------------------------------------------------

    def _init_patient_split(self, split: str, patient_splits_path: str):
        """Initialise using a patient-level split mapping file."""
        # Load the split mapping (cached on the class to avoid re-reading)
        if not hasattr(self.__class__, "_patient_split_map"):
            with open(patient_splits_path) as f:
                data = json.load(f)
            self.__class__._patient_split_map: Dict[str, str] = data["splits"]
            print(
                f"  Patient split loaded from {patient_splits_path} "
                f"({len(self.__class__._patient_split_map)} patients)"
            )

        split_map = self.__class__._patient_split_map

        # Pool ALL rows from both HF splits and filter by patient assignment
        all_hf = self.__class__._hf_train, self.__class__._hf_test
        indices = []  # list of (hf_split_idx, row_idx)

        for hf_idx, hf_split in enumerate(all_hf):
            for row_idx in range(len(hf_split)):
                pid = hf_split[row_idx]["patient_id"]
                if split_map.get(pid) == split:
                    indices.append((hf_idx, row_idx))

        self._index_map = indices  # (hf_split_idx, row_idx) tuples
        print(f"  {split} split: {len(indices)} QA pairs (patient-disjoint)")

    def _init_legacy_split(self, split: str):
        """Initialise using the original HF train/test split (backward compat)."""
        if split == "train":
            hf_data = self.__class__._hf_train
        else:
            hf_data = self.__class__._hf_test

        # Build an index map compatible with the patient-split code path
        hf_idx = 0 if split == "train" else 1
        self._index_map = [(hf_idx, i) for i in range(len(hf_data))]
        print(f"  {split} split (legacy HF): {len(self._index_map)} QA pairs")

    # --- Lazy __getitem__ / __len__ ----------------------------------------

    @property
    def _hf_splits(self):
        """Return the two HF splits as a tuple for index-based lookup."""
        return (self.__class__._hf_train, self.__class__._hf_test)

    def __len__(self):
        return len(self._index_map)

    def __getitem__(self, idx):
        """Load and format a single sample lazily (audio loaded on-the-fly)."""
        hf_idx, row_idx = self._index_map[idx]
        row = self._hf_splits[hf_idx][row_idx]
        return self._format_sample(row)

    # ------------------------------------------------------------------
    # Dataset-source metadata (for balanced sampling / loss weighting)
    # ------------------------------------------------------------------

    def get_dataset_labels(self) -> List[str]:
        """Return the source dataset name for every sample index.

        This is a lightweight operation — only HF metadata is accessed,
        no audio is loaded.  The returned list is aligned with
        ``range(len(self))`` so that ``labels[i]`` is the dataset source
        for ``self[i]``.

        Returns:
            List of dataset source strings, e.g.
            ``['ICBHI', 'CirCor', 'KAUH', ...]``
        """
        labels: List[str] = []
        for hf_idx, row_idx in self._index_map:
            row = self._hf_splits[hf_idx][row_idx]
            labels.append(row.get("dataset", "unknown"))
        return labels

    def _format_sample(self, row):
        """Format sample and attach ``dataset_source`` metadata."""
        formatted = super()._format_sample(row)
        # Attach the source dataset name so the training loop can use it
        # for loss weighting without a second HF lookup.
        formatted["dataset_source"] = row.get("dataset", "unknown")
        return formatted

    def _load_splits(self) -> Tuple[Dataset, Dataset, Dataset]:
        """Load train/val/test splits (legacy interface for QADataset base class).

        NOTE: This method is not used by the lazy-loading code path.
        The actual split logic is in ``_init_patient_split`` (recommended)
        or ``_init_legacy_split`` (backward compat).
        """
        print("Loading CaReSound dataset from HuggingFace...")
        dataset = load_dataset("tsnngw/CaReSound", cache_dir=self.cache_dir)
        train_data = dataset["train"]
        test_data = dataset["test"]
        val_data = test_data
        print(f"Loaded {len(train_data)} training samples")
        print(f"Loaded {len(test_data)} test samples")
        return train_data, val_data, test_data

    def _get_answer(self, row) -> str:
        """Get the answer from the row."""
        return row["answer"]

    def _get_pre_prompt(self, row) -> str:
        """Get the pre-prompt for medical audio QA."""
        dataset_name = row.get("dataset", "medical")
        return f"Listen to the following {dataset_name} auscultation audio and answer the diagnostic question."

    def _get_post_prompt(self, row) -> str:
        """Get the question as post-prompt."""
        question = row["question"]
        return f"Question: {question}\nAnswer:"

    def _get_text_time_series_prompt_list(self, row) -> List[TextTimeSeriesPrompt]:
        """
        Load and return the audio as a time series prompt.
        
        Handles multiple audio files per patient_id (e.g., for CirCor dataset:
        patient_id_AV.wav, patient_id_MV.wav, patient_id_PV.wav).
        
        For SPRSound: Merges segmented audio files back into coherent recordings.
        SPRSound files are named: {PatientID}_{Timestamp}_{Type}_{Position}_{ClipID}.wav
        Segments are grouped by position and merged with crossfade for smooth transitions.
        
        Supports multiple naming strategies to avoid collisions:
        1. {dataset}_{patient_id}.wav (dataset_prefix)
        2. {dataset}/{patient_id}.wav (dataset_subdir)
        3. {patient_id}_{dataset}.wav (dataset_suffix)
        4. {patient_id}.wav (patient_id_only - default)
        """

        patient_id = row["patient_id"]
        dataset_name = row.get("dataset", "Medical")
        
        # Special handling for SPRSound: merge segments
        if dataset_name.lower() == "sprsound":
            return self._load_sprsound_merged(patient_id, dataset_name)

        # Try different possible audio file extensions
        possible_extensions = [".wav", ".flac", ".mp3", ".ogg"]
        
        audio_prompts = []
        found_any = False

        # Try multiple naming strategies to handle different organization schemes
        # Strategy 1: Dataset prefix (e.g., ICBHI_12345.wav, CirCor_12345_AV.wav)
        # Strategy 2: Dataset subdirectory (e.g., ICBHI/12345.wav, CirCor/12345_AV.wav)
        # Strategy 3: Dataset suffix (e.g., 12345_ICBHI.wav, 12345_AV_CirCor.wav)
        # Strategy 4: Patient ID only (e.g., 12345.wav, 12345_AV.wav) - default fallback
        
        naming_strategies = [
            # (base_pattern, use_dataset, use_subdir)
            (f"{{dataset}}_{{patient_id}}", True, False),  # dataset_prefix
            (f"{{patient_id}}", False, True),  # dataset_subdir (will check subdir)
            (f"{{patient_id}}_{{dataset}}", True, False),  # dataset_suffix
            (f"{{patient_id}}", False, False),  # patient_id_only (fallback)
        ]

        # Strategy: Find ALL files matching patient_id pattern (with any suffix or no suffix)
        # This handles:
        # - CirCor: patient_id_AV.wav, patient_id_MV.wav, patient_id_PV.wav
        # - SPRSound: patient_id_suffix1.wav, patient_id_suffix2.wav, etc.
        # - Any dataset with multiple files per patient_id
        # - Also handles: {dataset}/{patient_id}.wav (no suffixes)
        
        import glob
        
        for pattern, use_dataset, use_subdir in naming_strategies:
            if use_subdir:
                # Check in dataset subdirectory: {dataset}/{patient_id}*.wav
                # First try with suffixes (for multiple files per patient)
                search_patterns = [
                    os.path.join(self.audio_dir, dataset_name, f"{patient_id}_*{ext}")
                    for ext in possible_extensions
                ]
                # Also try exact match (for single file per patient)
                search_patterns.extend([
                    os.path.join(self.audio_dir, dataset_name, f"{patient_id}{ext}")
                    for ext in possible_extensions
                ])
            elif use_dataset:
                # Include dataset in filename: {dataset}_{patient_id}_*.wav
                if "dataset" in pattern:
                    search_patterns = [
                        os.path.join(self.audio_dir, f"{dataset_name}_{patient_id}_*{ext}")
                        for ext in possible_extensions
                    ]
                else:
                    search_patterns = [
                        os.path.join(self.audio_dir, f"{patient_id}_*{ext}")
                        for ext in possible_extensions
                    ]
            else:
                # Just patient_id: {patient_id}_*.wav (with suffixes)
                search_patterns = [
                    os.path.join(self.audio_dir, f"{patient_id}_*{ext}")
                    for ext in possible_extensions
                ]
                # Also try exact match (no suffix)
                search_patterns.extend([
                    os.path.join(self.audio_dir, f"{patient_id}{ext}")
                    for ext in possible_extensions
                ])
            
            # Find all matching files
            matching_files = []
            for search_pattern in search_patterns:
                matching_files.extend(glob.glob(search_pattern))
            
            # Process each matching file
            for candidate_path in matching_files:
                if os.path.exists(candidate_path):
                    try:
                        # Extract suffix from filename for description
                        filename = os.path.basename(candidate_path)
                        # Remove extension
                        name_without_ext = os.path.splitext(filename)[0]
                        
                        # Extract suffix (everything after patient_id)
                        if use_dataset and "dataset" in pattern:
                            # Format: {dataset}_{patient_id}_{suffix}
                            prefix = f"{dataset_name}_{patient_id}_"
                        elif use_dataset:
                            # Format: {patient_id}_{suffix}_{dataset}
                            prefix = f"{patient_id}_"
                        else:
                            # Format: {patient_id}_{suffix}
                            prefix = f"{patient_id}_"
                        
                        if name_without_ext.startswith(prefix):
                            suffix_part = name_without_ext[len(prefix):]
                            # Remove dataset suffix if present
                            if use_dataset and f"_{dataset_name}" in suffix_part:
                                suffix_part = suffix_part.replace(f"_{dataset_name}", "")
                        else:
                            suffix_part = ""
                        
                        # Load and preprocess audio
                        waveform, sr = load_audio(candidate_path, self.sample_rate)
                        waveform = preprocess_audio(
                            waveform,
                            sample_rate=sr,
                            target_sample_rate=self.sample_rate,
                            normalize=True,
                            to_mono=True,
                            max_length=self.max_audio_length,
                        )
                        
                        # Keep as numpy float32 (NOT .tolist() which creates a
                        # bloated Python list of ~36 bytes/float vs 4 bytes/float)
                        audio_data = waveform.numpy()
                        
                        # Create descriptive text with per-clip metadata
                        if suffix_part:
                            if dataset_name.upper() == "ICBHI":
                                # ICBHI: parse chest location from filename
                                location_name = _parse_icbhi_suffix(suffix_part)
                            else:
                                # CirCor / others: map common valve suffixes.
                                # CirCor files may have numbered variants:
                                #   AV.wav, AV_1.wav, AV_2.wav, Phc_1.wav, …
                                # We match on the leading code before any "_N".
                                _VALVE_MAP = {
                                    "AV": "Aortic Valve",
                                    "MV": "Mitral Valve",
                                    "PV": "Pulmonic Valve",
                                    "TV": "Tricuspid Valve",
                                    "Phc": "Precordial",
                                }
                                # Extract leading code (e.g. "AV" from "AV_2")
                                valve_code = suffix_part.split("_")[0]
                                location_name = _VALVE_MAP.get(
                                    valve_code,
                                    _VALVE_MAP.get(
                                        suffix_part,
                                        suffix_part.replace("_", " ").title(),
                                    ),
                                )
                            description = f"{dataset_name} {location_name} auscultation audio"
                        else:
                            description = f"{dataset_name} auscultation audio"
                        
                        audio_prompts.append(
                            TextTimeSeriesPrompt(description, audio_data)
                        )
                        found_any = True
                    except Exception as e:
                        print(f"Error loading audio {candidate_path}: {e}")
                        continue
            
            if found_any:
                # Found files with this strategy, done searching
                break

        # If no files with suffixes found, try exact patient_id match (single file per patient)
        if not found_any:
            for ext in possible_extensions:
                # Try each naming strategy
                for pattern, use_dataset, use_subdir in naming_strategies:
                    if use_subdir:
                        # Check in dataset subdirectory
                        candidate_path = os.path.join(
                            self.audio_dir, 
                            dataset_name, 
                            f"{patient_id}{ext}"
                        )
                    elif use_dataset:
                        # Include dataset in filename
                        if "dataset" in pattern:
                            candidate_path = os.path.join(
                                self.audio_dir,
                                pattern.format(dataset=dataset_name, patient_id=patient_id) + ext
                            )
                        else:
                            candidate_path = os.path.join(
                                self.audio_dir,
                                pattern.format(patient_id=patient_id) + ext
                            )
                    else:
                        # Just patient_id
                        candidate_path = os.path.join(self.audio_dir, f"{patient_id}{ext}")
                    
                    if os.path.exists(candidate_path):
                        try:
                            # Load and preprocess audio
                            waveform, sr = load_audio(candidate_path, self.sample_rate)
                            waveform = preprocess_audio(
                                waveform,
                                sample_rate=sr,
                                target_sample_rate=self.sample_rate,
                                normalize=True,
                                to_mono=True,
                                max_length=self.max_audio_length,
                            )

                            audio_prompts.append(
                                TextTimeSeriesPrompt(
                                    f"{dataset_name} auscultation audio",
                                    waveform.numpy(),
                                )
                            )
                            found_any = True
                            break  # Found file with this strategy, done
                        except Exception as e:
                            print(f"Error loading audio {candidate_path}: {e}")
                            continue
                if found_any:
                    # Found file, done searching
                    break

        if not found_any:
            print(f"Warning: No audio files found for patient {patient_id} in {self.audio_dir}")
            print(f"  Tried:")
            print(f"    - Valve-specific: {patient_id}_AV.wav, {patient_id}_MV.wav, {patient_id}_PV.wav, {patient_id}_TV.wav")
            print(f"    - Direct match: {patient_id}.wav, {patient_id}.flac, {patient_id}.mp3, {patient_id}.ogg")
            # Return silent audio as fallback
            return [TextTimeSeriesPrompt("Medical audio", np.zeros(16000, dtype=np.float32))]

        # --- Clip sampling for patients with many recordings ----------------
        # During training: randomly sample k clips so different epochs see
        #   different subsets → full coverage over time.
        # During evaluation: deterministic first-k for reproducibility.
        k = self.max_clips_per_patient
        if k is not None and len(audio_prompts) > k:
            if self.split == "train":
                audio_prompts = random.sample(audio_prompts, k)
            else:
                audio_prompts = audio_prompts[:k]

        return audio_prompts

    def _load_sprsound_merged(self, patient_id: str, dataset_name: str) -> List[TextTimeSeriesPrompt]:
        """
        Load and merge SPRSound segments for a patient.
        
        SPRSound files are segmented breath recordings. This method:
        1. Finds all segments for the patient
        2. Groups by recording position (different lung lobes)
        3. Sorts by timestamp and clip_id
        4. Merges with crossfade for smooth transitions
        5. Handles overlaps (crops overlap region) and gaps (inserts silence)
        
        Args:
            patient_id: Patient ID to load
            dataset_name: Dataset name (should be "SPRSound")
            
        Returns:
            List of TextTimeSeriesPrompt, one per recording position
        """
        import glob
        audio_prompts = []
        
        # Try to find SPRSound segments
        merged_results = load_and_merge_sprsound_patient(
            audio_dir=self.audio_dir,
            patient_id=patient_id,
            target_sample_rate=self.sample_rate,
            crossfade_ms=10.0,  # 10ms crossfade for smooth transitions
            insert_gaps=True,   # Insert silence for time gaps
            max_gap_seconds=2.0,  # Cap silence at 2 seconds
            merge_positions=False  # Keep positions separate (different lung lobes)
        )
        
        if merged_results:
            # Successfully found and merged SPRSound segments
            for position, (merged_waveform, segment_info) in merged_results.items():
                if len(merged_waveform) == 0:
                    continue
                    
                # Preprocess merged audio (normalize, truncate if needed)
                processed = preprocess_audio(
                    merged_waveform,
                    sample_rate=self.sample_rate,
                    target_sample_rate=self.sample_rate,
                    normalize=True,
                    to_mono=True,
                    max_length=self.max_audio_length,
                )
                
                # Create description with position info
                position_desc = get_position_description(position)
                num_segments = len(segment_info)
                duration = len(processed) / self.sample_rate
                description = f"{dataset_name} respiratory audio - {position_desc} ({num_segments} segments merged, {duration:.1f}s)"
                
                audio_prompts.append(
                    TextTimeSeriesPrompt(description, processed.numpy())
                )
            
            if audio_prompts:
                return audio_prompts
        
        # Fallback: Try to find pre-merged or any files matching patient_id
        # Look for: {patient_id}.wav or {patient_id}_*.wav
        possible_extensions = [".wav", ".flac", ".mp3", ".ogg"]
        
        # Try in SPRSound subdirectory first
        search_dirs = [
            os.path.join(self.audio_dir, "SPRSound"),
            self.audio_dir
        ]
        
        for search_dir in search_dirs:
            if not os.path.exists(search_dir):
                continue
            
            # Find all files where patient_id is the first part (before _)
            for ext in possible_extensions:
                # Pattern: patient_id_*.wav (e.g., 40069321_p4.wav, 40069321_AV.wav)
                pattern = os.path.join(search_dir, f"{patient_id}_*{ext}")
                matching_files = glob.glob(pattern)
                
                # Also check exact match: patient_id.wav
                exact_match = os.path.join(search_dir, f"{patient_id}{ext}")
                if os.path.exists(exact_match):
                    matching_files.append(exact_match)
                
                for candidate_path in matching_files:
                    try:
                        waveform, sr = load_audio(candidate_path, self.sample_rate)
                        waveform = preprocess_audio(
                            waveform,
                            sample_rate=sr,
                            target_sample_rate=self.sample_rate,
                            normalize=True,
                            to_mono=True,
                            max_length=self.max_audio_length,
                        )
                        
                        # Extract suffix from filename for description
                        filename = os.path.basename(candidate_path)
                        name_without_ext = os.path.splitext(filename)[0]
                        
                        if name_without_ext == patient_id:
                            # Exact match, no suffix
                            description = f"{dataset_name} respiratory audio"
                        else:
                            # Has suffix (e.g., _p4, _AV)
                            suffix = name_without_ext.replace(f"{patient_id}_", "")
                            suffix_desc = get_position_description(suffix)
                            description = f"{dataset_name} respiratory audio - {suffix_desc}"
                        
                        audio_prompts.append(
                            TextTimeSeriesPrompt(description, waveform.numpy())
                        )
                    except Exception as e:
                        print(f"Error loading audio {candidate_path}: {e}")
                        continue
                
                if audio_prompts:
                    return audio_prompts
        
        # No files found
        print(f"Warning: No SPRSound audio files found for patient {patient_id}")
        print(f"  Looked for: {patient_id}_*.wav and {patient_id}.wav")
        return [TextTimeSeriesPrompt("SPRSound audio", np.zeros(16000, dtype=np.float32))]
